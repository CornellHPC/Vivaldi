int main(int argc, char* argv[]) {
  MPI_Init(&argc, &argv);
  MPI_Comm comm = MPI_COMM_WORLD;

  int rank, size;
  MPI_Comm_rank(comm, &rank);
  MPI_Comm_size(comm, &size);

  /** Const */
  bool s = true;
  int m = 33;
  int n = 8;
  int k = 2;

  /** WARNING: Test as of now needs to be run with 4 procs */
  assert(size == 4 && "This test must be run with 4 processes.");
  V_t V(m, k, s, comm);
  check_v0(V);
  check_v_tiling(V, rank);
  int t = V.t;  // get this process tile size

  wake_gpus(rank);
  slate::gpu_aware_mpi(true);

  Handle handle(s);


  auto PT = load_matrix("../data/randi", m, n, comm);
  DnMat_t K(m, t, compute_kernel_matrix(PT, 1.0f, 1.0f, 1.0f));

  PT.releaseWorkspace();
  check_k(K, rank);

  DnMat_t E(k, t);
  DnVec_t z(t);
  DnVec_t c(k);

  spmm(handle, V, K, E);
  check_e1(E, rank);

  compute_z(V, E, z);
  check_z1(z, rank);

  spmv(handle, V, z, c);
  sum_vec(c, comm);
  check_c1(c);

  reinit_V(E, c, V);
  check_v1(V);

  spmm(handle, V, K, E);
  check_e2(E, rank);

  compute_z(V, E, z);
  check_z2(z, rank);

  spmv(handle, V, z, c);
  sum_vec(c, comm);
  check_c2(c);

  reinit_V(E, c, V);
  check_v2(V);

  MPI_Finalize();
  return 0;
}
